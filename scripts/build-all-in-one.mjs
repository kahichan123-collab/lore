// Regenerates supabase/install/lore_all_in_one.sql from the numbered
// migrations. Run after editing any migration:
//   npm run migrations:build
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const files = [
  "0001_schema.sql",
  "0002_rls.sql",
  "0003_admin_analytics.sql",
  "0004_rate_limits.sql",
  "0005_stage1_spec_gaps.sql",
  "0006_stage2_7.sql",
];

const parts = [
  "-- 古問 LORE — one-file install (generated from 0001–0006)",
  "-- Paste this entire file into the Supabase SQL Editor on a NEW project and click Run.",
  "-- Do not also run the numbered migration files on the same project.",
  "-- Generated by `npm run migrations:build`; edit the numbered files instead.",
  "",
];

for (const file of files) {
  parts.push("", "-- =============================================================");
  parts.push(`-- ${file}`);
  parts.push("-- =============================================================");
  parts.push(readFileSync(join(process.cwd(), "supabase/migrations", file), "utf8"));
}

writeFileSync(join(process.cwd(), "supabase/install/lore_all_in_one.sql"), parts.join("\n"), "utf8");
console.log(`Wrote supabase/install/lore_all_in_one.sql (${files.length} migrations).`);
